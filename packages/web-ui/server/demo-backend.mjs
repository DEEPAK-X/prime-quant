const STRATEGY_PY = `# eurusd_m5_mean_reversion.py
# Clean spec: no lookahead. Signals computed on closed bars; entries fill at
# the next bar open via the engine execution model (slippage + variable spread).
from primequant.strategy.base import StrategySpec
from primequant.backtest.engine import run_backtest
from primequant.validate.pipeline import run_validation_pipeline

spec = StrategySpec(
    symbol="EURUSD",
    timeframe="M5",
    asset_class="forex",
    risk_per_trade_pct=0.5,
    stop_loss_atr=2.0,
    take_profit_atr=3.0,
    lot_size_units=100_000,
)

def signals(df):
    rsi = df["close"].rolling(14).mean()
    return (df["close"] < rsi).astype(int)

result = run_backtest(spec, signals)
gate = run_validation_pipeline(spec, result)
print(gate.summary_json())
`;

const EXPERT_MQ5 = `//+------------------------------------------------------------------+
//| EURUSD_M5_MeanReversion_EA.mq5                                  |
//| Generated by primequant.report.tearsheet export                 |
//+------------------------------------------------------------------+
input double RiskPerTradePct = 0.5;
input int    AtrPeriod       = 14;
input double AtrStopMult     = 2.0;
input double AtrTargetMult   = 3.0;

double g_atr[];
int    g_atrHandle;

int OnInit() {
   g_atrHandle = iATR(_Symbol, PERIOD_M5, AtrPeriod);
   if (g_atrHandle == INVALID_HANDLE) return INIT_FAILED;
   ArraySetAsSeries(g_atr, true);
   return INIT_SUCCEEDED;
}

void OnTick() {
   if (CopyBuffer(g_atrHandle, 0, 0, 1, g_atr) < 1) return;
   if (PositionSelect(_Symbol)) return;          // one position at a time
   double atr = g_atr[0];
   double risk = AccountInfoDouble(ACCOUNT_BALANCE) * RiskPerTradePct / 100.0;
   double lots = NormalizeDouble(risk / (atr * AtrStopMult * _Point * 100000), 2);
   // Entry executes at the next tick after the signal bar closes:
   // strategy bar state is only consumed from closed bars (Close[1]).
   if (Close[1] < iMA(_Symbol, PERIOD_M5, 14, 0, MODE_SMA, PRICE_CLOSE, 1)) {
      double sl = Close[1] - atr * AtrStopMult * _Point;
      double tp = Close[1] + atr * AtrTargetMult * _Point;
      Trade.Buy(lots, _Symbol, 0.0, sl, tp, "mean-reversion");
   }
}
`;

