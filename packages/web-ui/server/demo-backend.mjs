const roomLogs = new Map(ROOMS.map((room) => [room.id, []]));
let roomSeq = 0;

function postRoomMessage(room, from, text) {
	const message = {
		type: "room_message",
		room,
		id: `rm-${++roomSeq}`,
		from,
		text,
		ts: new Date().toISOString(),
	};
	const log = roomLogs.get(room) ?? [];
	log.push(message);
	if (log.length > 200) log.splice(0, log.length - 200);
	roomLogs.set(room, log);
	return message;
}

const SEEDED_ROOM_POSTS = [
	["risk-management", "watcher://risk", "@You daily-loss guard armed at 1% equity. Drawdown 2.4% — inside the 5% limit."],
	["research", "watcher://research", "triage complete: 2 of 5 queued ideas passed the validation gate. Top candidate: EURUSD M5 rsi(14) mean reversion (dsr 1.32, pbo 0.11)."],
	["system-updates", "bridge", "demo backend seeded — rooms, watchers, and pipeline fixtures live."],
];

let watcherTick = 0;

function sendJson(response, status, body) {
	response.writeHead(status, { "content-type": "application/json" });
	response.end(JSON.stringify(body));
}

function broadcast(clients, event) {
	const payload = JSON.stringify(event);
	for (const client of clients) {
		if (client.readyState === client.OPEN) client.send(payload);
	}
}

const server = createServer((request, response) => {
	const url = new URL(request.url ?? "/", `http://${request.headers.host ?? "localhost"}`);

	if (url.pathname === "/api/subagents" && request.method === "GET") {
		sendJson(response, 200, { subagents: SUBAGENTS });
		return;
	}
	if (url.pathname === "/api/artifacts" && request.method === "GET") {
		const kind = url.searchParams.get("kind");
		const artifacts = kind === "mq5" ? MQ5_ARTIFACTS : PY_ARTIFACTS;
		sendJson(response, 200, { artifacts });
		return;
	}
	if (url.pathname === "/api/tearsheet/latest" && request.method === "GET") {
		sendJson(response, 200, { url: "/artifacts/tearsheet.html" });
		return;
	}
	if (url.pathname === "/api/rooms" && request.method === "GET") {
		sendJson(response, 200, {
			rooms: ROOMS.map((room) => ({ ...room, messages: (roomLogs.get(room.id) ?? []).length })),
		});
		return;
	}
	const roomMatch = /^\/api\/rooms\/([a-z0-9-]+)\/messages$/.exec(url.pathname);
	if (roomMatch) {
		const roomId = roomMatch[1];
		if (!roomLogs.has(roomId)) {
			sendJson(response, 404, { error: "unknown room" });
			return;
		}
		if (request.method === "GET") {
			sendJson(response, 200, { room: roomId, messages: roomLogs.get(roomId) });
			return;
		}
		if (request.method === "POST") {
			let body = "";
			request.on("data", (chunk) => (body += chunk));
			request.on("end", () => {
				try {
					const parsed = JSON.parse(body);
					if (typeof parsed.from !== "string" || typeof parsed.text !== "string") {
						sendJson(response, 400, { error: "from and text are required" });
						return;
					}
					const message = postRoomMessage(roomId, parsed.from, parsed.text);
					broadcast(wss.clients, message);
					sendJson(response, 201, { message });
				} catch {
					sendJson(response, 400, { error: "invalid JSON body" });
				}
			});
			return;
		}
	}
	if (url.pathname === "/artifacts/tearsheet.html" && request.method === "GET") {
		response.writeHead(200, { "content-type": "text/html; charset=utf-8" });
		response.end(TEARSHEET_HTML);
		return;
	}
	sendJson(response, 404, { error: "not found" });
});

const wss = new WebSocketServer({ server, path: "/ws" });

let runCounter = 0;

/** Simulates one orchestrator pipeline run: AST check -> backtest -> CPCV gate. */
function runDemoPipeline(clients) {
	runCounter += 1;
	const runId = `run-${Date.now()}-${runCounter}`;
	const step = (name, status, detail) =>
		broadcast(clients, { type: "step", id: `${runId}-${name}`, name, status, detail });

	const queue = [
		[0, () => step("ast_check", "running")],
		[450, () => step("ast_check", "done", "no lookahead violations")],
		[650, () => broadcast(clients, { type: "chat", role: "assistant", text: "ast_check: passed — no future-indexing or leakage patterns in the strategy source." })],
		[950, () => step("backtest", "running")],
		[1400, () => step("backtest", "done", "412 trades · sharpe 1.84")],
		[1600, () => step("cpcv_gate", "running")],
		[2050, () => step("cpcv_gate", "done", "dsr 1.32 · pbo 0.11")],
		[2250, () => broadcast(clients, { type: "chat", role: "assistant", text: `Backtest complete. Summary card for ${runId}:\n\n\`\`\`json\n{\n  "status": "success",\n  "metrics": {\n    "sharpe_ratio": 1.84,\n    "sortino_ratio": 2.12,\n    "calmar_ratio": 1.95,\n    "max_drawdown_pct": 4.8,\n    "profit_factor": 1.72,\n    "win_rate": 0.54,\n    "expectancy_usd": 28.5,\n    "trades_count": 412\n  },\n  "validation_gate": { "passed": true, "deflated_sharpe": 1.32, "pbo": 0.11, "oos_degradation_pct": 22.4 }\n}\n\`\`\`\nEquity curve, drawdown heatmap and DSR card are in the tearsheet pane. Raw frames stay bound in the kernel.` })],
		[2350, () => broadcast(clients, { type: "subagent", id: "sub-1", name: "worker://eurusd-m5-scan", tier: "worker", status: "DONE", tokensPerMin: 12400, task: "param sweep: rsi(14) mean reversion on EURUSD M5" })],
		[2350, () => broadcast(clients, { type: "subagent", id: "sub-4", name: "worker://optimize-eurusd-m5", tier: "worker", status: "RUNNING", tokensPerMin: 15600, task: "optuna sweep: atr multiples" })],
		[2450, () => broadcast(clients, { type: "tearsheet", url: "/artifacts/tearsheet.html" })],
		[2550, () => broadcast(clients, { type: "artifact", kind: "py", name: "eurusd_m5_mean_reversion_v2.py", content: STRATEGY_PY })],
	];
	for (const [delay, fn] of queue) {
		setTimeout(fn, delay);
	}
}

wss.on("connection", (socket) => {
	socket.on("message", (data) => {
		let payload;
		try {
			payload = JSON.parse(String(data));
		} catch {
			return;
		}
		if (payload?.type === "chat" && typeof payload.text === "string") {
			runDemoPipeline([socket]);
		}
	});

	// Welcome, then kick off a self-running demo cycle so the GUI is alive
	// immediately after connect.
	broadcast([socket], { type: "rooms_state", rooms: ROOMS });
	for (const [room, from, text] of SEEDED_ROOM_POSTS) {
		const existing = (roomLogs.get(room) ?? []).find((message) => message.from === from && message.text === text);
		broadcast([socket], existing ?? postRoomMessage(room, from, text));
	}
	broadcast([socket], {
		type: "chat",
		role: "assistant",
		text: "orchestrator online. Demo backend seeded — I'll start a research run on EURUSD M5 (mean reversion) right away.",
	});
	setTimeout(() => runDemoPipeline([socket]), 700);

	// Watcher liveliness: a flow-watcher card every 45s into #alerts.
	const watcherTimer = setInterval(() => {
		watcherTick += 1;
		const z = (2.4 + Math.random() * 1.6).toFixed(1);
		const message = postRoomMessage(
			"alerts",
			"watcher://flow",
			`EURUSD M5 volume z-score ${z} (threshold 2.5) — ${Number(z) > 2.5 ? "anomaly flagged" : "within tolerance"} · tick ${watcherTick}`,
		);
		if (socket.readyState === socket.OPEN) broadcast([socket], message);
	}, 45000);
	socket.on("close", () => clearInterval(watcherTimer));
});

server.listen(PORT, () => {
	console.log(`[demo-backend] listening on http://localhost:${PORT} (ws: /ws)`);
});
